-- Estadísticas y registro de eventos de juegos para el simulador escolar.
create table if not exists public.estadisticas_juegos (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  game_name text not null,
  event_type text not null default 'jugada',
  amount numeric(14,2) not null default 0,
  lost_amount numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_estadisticas_juegos_game on public.estadisticas_juegos(game_name);
create index if not exists idx_estadisticas_juegos_user on public.estadisticas_juegos(user_id);

alter table public.estadisticas_juegos enable row level security;

drop policy if exists estadisticas_juegos_insert_own on public.estadisticas_juegos;
create policy estadisticas_juegos_insert_own on public.estadisticas_juegos
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists estadisticas_juegos_select_authenticated on public.estadisticas_juegos;
create policy estadisticas_juegos_select_authenticated on public.estadisticas_juegos
  for select to authenticated using (true);

